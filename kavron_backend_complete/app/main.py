@app.websocket("/ws/events")
async def websocket_events(
    websocket: WebSocket,
):
    """
    Real-time KAVRON event stream.

    Frontend clients can connect to:
        ws://127.0.0.1:8000/ws/events
    """

    await websocket.accept()

    print(
        "[KAVRON] WebSocket client connected"
    )

    bus: EventBus = (
        websocket.app.state.event_bus
    )

    queue = await bus.subscribe(
        "*"
    )

    try:

        while True:

            event = await queue.get()

            await websocket.send_json(
                event
            )

    except WebSocketDisconnect:

        print(
            "[KAVRON] WebSocket client "
            "disconnected"
        )

    except Exception as exc:

        print(
            "[KAVRON] WebSocket error: "
            f"{exc}"
        )

    finally:

        try:

            await bus.unsubscribe(
                "*",
                queue,
            )

        except Exception as exc:

            print(
                "[KAVRON] WebSocket cleanup "
                f"warning: {exc}"
            )


