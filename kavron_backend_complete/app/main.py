ALLOWED_ORIGINS = [
    "http://localhost:8443",
    "http://127.0.0.1:8443",
    "http://localhost:5173",
    "http://127.0.0.1:5173",
]


try:

    configured_origins = (
        settings.origins
    )

    if isinstance(
        configured_origins,
        str,
    ):

        configured_origins = [
            origin.strip()
            for origin
            in configured_origins.split(",")
            if origin.strip()
        ]

    for origin in (
        configured_origins or []
    ):

        if (
            origin
            not in ALLOWED_ORIGINS
        ):

            ALLOWED_ORIGINS.append(
                origin
            )

except Exception as exc:

    print(
        "[KAVRON] Warning reading "
        f"configured CORS origins: {exc}"
    )


