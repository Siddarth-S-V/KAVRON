# CPU oversubscription guard: camera/inference workers are already threaded.
# Keep each native math backend from spawning a second large thread pool.
try:
    import cv2
    import torch
    _native_threads = int(os.getenv("KAVRON_CPU_THREADS", "0"))
    if _native_threads <= 0:
        _native_threads = max(1, min(4, (os.cpu_count() or 4) // 2))
    cv2.setNumThreads(_native_threads)
    torch.set_num_threads(_native_threads)
    try:
        torch.set_num_interop_threads(max(1, min(2, _native_threads)))
    except Exception:
        pass
except Exception:
    pass

