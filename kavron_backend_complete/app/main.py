# ============================================================
# EVENT HANDLER
# ============================================================

def _handle_event(
    event,
    events,
    bus,
    loop,
):
    """
    Handle events generated by the AI pipeline.

    Detection events are passed to the EventEngine.
    Every event is also published to the EventBus so that
    the WebSocket clients can receive it in real time.
    """

    try:
        if event.get("type") == "detection":
            asyncio.run_coroutine_threadsafe(
                events.handle_detection(event),
                loop,
            )

        asyncio.run_coroutine_threadsafe(
            bus.publish(event),
            loop,
        )

    except Exception as exc:
        print(
            f"[KAVRON] Event handler error: {exc}"
        )


